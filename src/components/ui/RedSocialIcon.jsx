function normalizarPlataforma(plataforma) {
  return String(plataforma || '')
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\s+/g, '');
}

export function RedSocialIcon({ plataforma, className = '' }) {
  const key = normalizarPlataforma(plataforma);
  const icon = ICONS[key] ?? ICONS[key.replace(/[^a-z]/g, '')];

  if (!icon) {
    return (
      <span className={`redSocialIcon redSocialIconFallback ${className}`.trim()} aria-hidden="true">
        {String(plataforma || '?').charAt(0).toUpperCase()}
      </span>
    );
  }

  return <span className={`redSocialIcon ${className}`.trim()}>{icon}</span>;
}

export function etiquetaRedSocial(plataforma) {
  const key = normalizarPlataforma(plataforma);
  if (key === 'x' || key === 'twitter') return 'X (Twitter)';
  return String(plataforma || 'Red social');
}
